static void check(const char *name, int ok)
{
	printf("CG-JPEG %-59s %s\n", name, ok ? "ok" : "FAIL");
	if (!ok) {
		failures++;
	}
}

static void check_near(const char *name, double got, double want)
{
	double d = got - want;

	if (d < 0) {
		d = -d;
	}
	printf("CG-JPEG %-59s %s (got %g, want %g ±12)\n", name, d <= 12.0 ? "ok" : "FAIL", got, want);
	if (!(d <= 12.0)) {
		failures++;
	}
}

static void pixel(CGContextRef c, int x, int y, unsigned char *out)
{
	unsigned char *d = CGBitmapContextGetData(c);

	memcpy(out, d + (size_t)y * CGBitmapContextGetBytesPerRow(c) + (size_t)x * 4, 4);
}

static CGImageRef decode(const unsigned char *bytes, size_t size)
{
	CGDataProviderRef provider = CGDataProviderCreateWithData(NULL, bytes, size, NULL);

	if (provider == NULL) {
		return NULL;
	}
	return CGImageCreateWithJPEGDataProvider(provider, NULL, false, kCGRenderingIntentDefault);
}

int main(void)
{
	static unsigned char buf[N * N * 4];
	CGImageRef image;
	CGContextRef c;

	image = decode(jpeg_16x16, sizeof(jpeg_16x16));
	check("a 16x16 JPEG decodes", image != NULL);
	check_near("...to its own width", (double)CGImageGetWidth(image), 16.0);
	check_near("...and height", (double)CGImageGetHeight(image), 16.0);
	check_near("...at 32 bits per pixel", (double)CGImageGetBitsPerPixel(image), 32.0);
	check("...premultiplied, which is the format these contexts draw",
	      CGImageGetAlphaInfo(image) == kCGImageAlphaPremultipliedFirst);

	/* THE IMAGE IS THE SAME SIZE AS THE SURFACE, so this is a 1:1 draw and the only mapping in
	 * play is the flip every image path in this library shares: the image's row 0 is the top. */
	memset(buf, 0, sizeof(buf));
	c = CGBitmapContextCreate(buf, N, N, 8, N * 4, CGColorSpaceCreateDeviceRGB(),
				  kCGImageAlphaPremultipliedFirst | kCGImageByteOrder32Little);
	CGContextDrawImage(c, CGRectMake(0.0, 0.0, (double)N, (double)N), image);
	pixel(c, 4, 4, p);
	check_near("the top-left quadrant draws RED", (double)p[2], 255.0);
	check("...and its green and blue are not", p[1] < 40 && p[0] < 40);
	pixel(c, 12, 4, p);
	check_near("the top-right quadrant draws GREEN", (double)p[1], 255.0);
	pixel(c, 4, 12, p);
	check_near("the bottom-left quadrant draws BLUE", (double)p[0], 255.0);
	pixel(c, 12, 12, p);
	check_near("...and the bottom-right YELLOW, which is red and green together", (double)p[2],
		   255.0);
	check_near("...with green too", (double)p[1], 255.0);
	pixel(c, 4, 4, p);
	check_near("EVERY PIXEL IS OPAQUE, as a JPEG has no alpha channel", (double)p[3], 255.0);
	CGImageRelease(image);
	CGContextRelease(c);

	/* --- and a corrupt file is REFUSED, NOT FATAL ----------------------------------------- */
	/* THE DECODER MUST INSTALL ITS OWN ERROR HANDLER TO GET PAST THIS LINE: libjpeg's default one
	 * calls exit(3), so a seam that forgot would kill the probe here — which is precisely the
	 * property being checked, since the assertion after it is only reachable if it survived. */
	check("a TRUNCATED JPEG is refused rather than exiting",
	      decode(jpeg_16x16, 200) == NULL);
	check("...and the process is still here to say so", 1);
	{
		CGFloat decode_array[8] = { 0 };
		CGDataProviderRef provider = CGDataProviderCreateWithData(NULL, jpeg_16x16,
									 sizeof(jpeg_16x16), NULL);

		check("a decode array is refused rather than ignored",
		      CGImageCreateWithJPEGDataProvider(provider, decode_array, false,
							kCGRenderingIntentDefault) == NULL);
		CGDataProviderRelease(provider);
	}

	printf("CG-JPEG: %s\n", failures == 0 ? "all checks passed" : "FAILURES");
	return failures;
}
